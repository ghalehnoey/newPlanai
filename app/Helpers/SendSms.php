<?php

namespace App\Helpers;

use Illuminate\Support\Facades\Http;
use Illuminate\Support\Facades\Log;
use Illuminate\Http\Client\RequestException;
use SimpleXMLElement; // ????? ??? ???? ??? ?? ???? XML

class SendSms
{
    /**
     * ????? ????? ???? ?? ??? SendByBaseNumber (SOAP)
     * * @param string $phone ????? ?????? (????: 0915...)
     * @param string $patternValue ????? ????? ???? (????: 559574)
     * @return bool
     */
    public static function send($phone, $patternValue)
    {
        // 1. ??????? API ?? ???? .env
        $apiKey       = config('services.payamak.password');
        $username     = config('services.payamak.username');
        $bodyId       = config('services.payamak.body_id'); 
        
        // ???? ???? SOAP API (???? ??? SendByBaseNumber)
        $url = 'http://api.payamak-panel.com/post/Send.asmx'; 

        // 2. ???? ???? XML ???? ???????? ??? SendByBaseNumber
        // * ????: ?? ????? ???? ?? ???? ?? <text><string>...</string></text> ???? ???????.
        $xmlBody = '<?xml version="1.0" encoding="utf-8"?>
        <soap:Envelope xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:xsd="http://www.w3.org/2001/XMLSchema" xmlns:soap="http://schemas.xmlsoap.org/soap/envelope/">
          <soap:Body>
            <SendByBaseNumber xmlns="http://tempuri.org/">
              <username>' . $username . '</username>
              <password>' . $apiKey . '</password>
              <text>
                <string>' . $patternValue . '</string>
              </text>
              <to>' . $phone . '</to>
              <bodyId>' . $bodyId . '</bodyId>
            </SendByBaseNumber>
          </soap:Body>
        </soap:Envelope>';

        // ????????? ???? ???????? 
        $params = [
            'username'      => $username,
            'to'            => $phone,
            'bodyId'        => $bodyId, 
            'pattern_value' => $patternValue,
            'method'        => 'SendByBaseNumber (SOAP)'
        ];

        try {
            // 3. ????? ??????? ?? ?????? SOAP
            $response = Http::withHeaders([
                'Content-Type' => 'text/xml; charset=utf-8',
                'SOAPAction'   => 'http://tempuri.org/SendByBaseNumber', 
            ])->send('POST', $url, [
                'body' => $xmlBody
            ]);
            
            // 4. ????? ???? (SOAP)
            if ($response->successful()) {
                 // ???? XML ?? ??? ???????
                // ??? ???? XML ??????? ???? ?? ???? try/catch ???????
                $xmlResponse = simplexml_load_string($response->body());

                // ???? ?????? ??? ?????? ???? ??? SOAP ? tempuri ?? ??? ???????
                $xmlResponse->registerXPathNamespace('soap', 'http://schemas.xmlsoap.org/soap/envelope/');
                $xmlResponse->registerXPathNamespace('def', 'http://tempuri.org/');
                
                // ??? ????? ?? ?? ??????? ?? XPath ?????????
                $resultNode = $xmlResponse->xpath('//def:SendByBaseNumberResult');

                if (!empty($resultNode)) {
                    // ????? ????? ?? ?? ????? ???? ????????? (???? ??? Message ID ????)
                    $result = (string)$resultNode[0];
                    
                    // ????? ?????? (MessageID) ???? ????? ?????? ?? 10 ??? ???.
                    // ????? ??? ????? ???? (????? 100-) ?? ???? ?????.
                    if (strlen($result) > 10 && is_numeric($result)) {
                         // ????? ??????????? ???
                         Log::info('SMS Sent Successfully (Pattern SOAP)', ['tracking_id' => $result, 'params' => $params]);
                         return true;
                    }
                    
                    // ??? ?? ???? ?? ???? ??? (?? ???)
                    Log::error('Payamak-Panel API Failed (SOAP Result Error - Code: ' . $result . ')', [
                        'status'       => $response->status(), 
                        'api_response' => $response->body(), 
                        'url'          => $url,
                        'params'       => $params
                    ]);
                    return false; 
                }
                
                // ??? ??? ????? ???? ??? (???????? ?????? XML ????????? ???)
                Log::error('Payamak-Panel API Failed (Result Node Missing)', [
                    'status'       => $response->status(), 
                    'api_response' => $response->body(), 
                    'url'          => $url,
                    'params'       => $params
                ]);
                return false;

            } else {
                // ??? ?? ????? HTTP? 4xx ?? 5xx ???
                Log::error('Payamak-Panel API Failed (HTTP Status Error)', [
                    'status' => $response->status(), 
                    'api_response' => $response->body(), 
                    'url' => $url,
                    'params' => $params
                ]);
                return false;
            }

        } catch (RequestException $e) {
            // ??? ?? ????? ????
             Log::critical('SMS Network Connection Error', [
                 'exception' => $e->getMessage(), 
                 'url' => $url
             ]);
             return false;
        } catch (\Exception $e) {
            // ???? ????? (??? ???? SimpleXML)
             Log::critical('General SMS Error in SendSms Helper', [
                 'exception' => $e->getMessage()
             ]);
             return false;
        }
    }
}