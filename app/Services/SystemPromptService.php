    public function getSystemPrompt(): string
    {
        try {
            $row = DB::table("settings")->where("key", "system_prompt")->value("value");
            if ($row && trim($row) !== "") {
                return $row;
            }
        } catch (\Throwable $e) {
        }
        return $this->defaultPrompt;
    }

    public function getDefaultPrompt(): string
    {
        return $this->defaultPrompt;
    }

    public function save(string $prompt): void
    {
        DB::table("settings")->updateOrInsert(
            ["key" => "system_prompt"],
            ["value" => $prompt, "updated_at" => now()]
        );
    }

    public function getTopicRestriction(): string
    {
        try {
            return (string) DB::table("settings")->where("key", "bot_topic_restriction")->value("value");
        } catch (\Throwable $e) {
            return "";
        }
    }

    public function saveTopicRestriction(string $text): void
    {
        DB::table("settings")->updateOrInsert(
            ["key" => "bot_topic_restriction"],
            ["value" => $text, "updated_at" => now()]
        );
    }
