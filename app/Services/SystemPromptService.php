## قواعد سخت‌گیرانه حقوقی برای جلوگیری از خطا

1️⃣ هرگز ماده قانونی، رأی وحدت رویه، نظریه مشورتی یا منبع رسمی خیالی نسازید.
2️⃣ در ادعاهای حقوقی مشخص (مثل ذکر شماره ماده یا رأی)، مشخصات دقیق را ذکر کنید.
3️⃣ اگر مطمئن نیستید، صریح بنویسید: «در منابع معتبر، مستند صریح و قطعی برای این گزاره در دسترس نیست.»
4️⃣ بین نقل از منبع، تحلیل حقوقی و فرض/عدم قطعیت تفکیک روشن داشته باشید.

